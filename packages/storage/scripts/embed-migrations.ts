/**
 * Converts drizzle-kit output (drizzle/*.sql + meta/_journal.json) into src/migrations.generated.ts so
 * the bundled CLI carries its migrations without reading files from disk.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const journal = JSON.parse(readFileSync(join(root, 'drizzle/meta/_journal.json'), 'utf8')) as {
  entries: Array<{ idx: number; tag: string }>;
};
const migrations = journal.entries
  .sort((a, b) => a.idx - b.idx)
  .map((entry) => ({
    tag: entry.tag,
    statements: readFileSync(join(root, 'drizzle', `${entry.tag}.sql`), 'utf8')
      .split('--> statement-breakpoint')
      .map((s) => s.trim())
      .filter(Boolean),
  }));
const body = `// Generated by scripts/embed-migrations.ts from drizzle-kit output. Do not edit.\nexport const MIGRATIONS: ReadonlyArray<{ tag: string; statements: readonly string[] }> = ${JSON.stringify(migrations, null, 2)};\n`;
writeFileSync(join(root, 'src/migrations.generated.ts'), body);
console.log(`embedded ${migrations.length} migration(s)`);
